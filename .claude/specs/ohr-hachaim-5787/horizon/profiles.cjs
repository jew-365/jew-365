// Writes src/data/horizonProfiles.ts: the terrain horizon of each printed city's observer point, the luach's visible
// sunrise model (README.md, Horizon reconstruction). Usage: node profiles.cjs, after fetch-dem.sh; then prettier.
// Each point is the one fitted on every printed sunrise (fit.cjs --all); change one only with a new fit.
const fs = require('fs');
const path = require('path');
const { elev, horizon } = require('./horizon.cjs');

const POINTS = [
  { cityId: 'jerusalem', lat: 31.8253, lng: 35.2317, k: 0.13 },
  { cityId: 'tel-aviv', lat: 32.0913, lng: 34.8358, k: 0.13 },
  { cityId: 'haifa', lat: 32.769, lng: 35.018, k: 0.13 },
  { cityId: 'beer-sheva', lat: 31.2368, lng: 34.7913, k: 0.13 },
];
const FROM_AZ = 50, TO_AZ = 130, STEP = 0.1; // every sunrise azimuth in Israel, with the search's margin

const entries = POINTS.map(({ cityId, lat, lng, k }) => {
  const h = Math.round(elev(lat, lng)) + 2;
  const angles = [];
  for (let i = 0; i <= Math.round((TO_AZ - FROM_AZ) / STEP); i++) angles.push(Math.round(horizon(lat, lng, h, FROM_AZ + i * STEP, k) * 1000));
  return `  '${cityId}': { lat: ${lat}, lng: ${lng}, angles: '${angles.join(',')}' },`;
});
const out = `// Generated by .claude/specs/ohr-hachaim-5787/horizon/profiles.cjs from the public SRTM terrain; do not edit.
// The apparent terrain horizon seen from each printed city's observer point (2 m above the ground, terrestrial
// refraction on an effective Earth radius), in thousandths of a degree, from ${FROM_AZ}° to ${TO_AZ}° azimuth every ${STEP}°.
export const HORIZON_FROM_AZ = ${FROM_AZ};
export const HORIZON_STEP_DEG = ${STEP};

export const HORIZON_PROFILES: Record<string, { lat: number; lng: number; angles: string }> = {
${entries.join('\n')}
};
`;
fs.writeFileSync(path.resolve(__dirname, '../../../../src/data/horizonProfiles.ts'), out);
console.log('wrote', out.length, 'bytes');
